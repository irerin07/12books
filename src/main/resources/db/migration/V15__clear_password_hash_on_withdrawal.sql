-- 탈퇴한 계정의 비밀번호 해시를 비울 수 있게 한다.
--
-- 탈퇴는 행을 지우지 않는다(V13). 그래서 보관 기간(1~3년) 동안 이메일·해시·프로필이 원형
-- 그대로 남아 있었는데, 그중 **해시는 쓸 일이 없다** — 탈퇴 계정은 로그인할 수 없고
-- 재발급도 막혀 있으므로 그 값으로 할 수 있는 일이 하나도 없다. 그런데 유출되면 같은
-- 비밀번호를 쓰는 다른 사이트로 넘어간다. 얻는 것 없이 위험만 지는 값이다.
--
-- 지우는 것은 **자격증명뿐**이다. 콘텐츠를 잇는 id와 운영 기록에 필요한 handle·display_name은
-- 그대로 둔다 — 그것들은 남아 있어야 할 이유가 분명하다. 이메일은 이번에 건드리지 않는다.
-- 재가입 확인이나 분쟁 대응에 쓸 여지가 있어 별도 판단이 필요하다.
--
-- 빈 문자열이 아니라 NULL인 이유: 빈 문자열은 "값이 있는데 비었다"로 읽혀 해시로 취급된다.
-- NULL은 "자격증명이 없다"를 그대로 말한다.

alter table users
    modify password_hash varchar(255) null;

-- 이미 탈퇴한 계정이 있다면 지금 비운다. 지난 탈퇴자의 해시를 남겨 둘 이유가 없다.
update users
set password_hash = null
where deleted_at is not null;
