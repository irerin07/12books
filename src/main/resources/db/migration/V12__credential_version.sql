-- 자격증명 번호. 이 사람의 비밀번호가 몇 번 바뀌었는가.
--
-- 세션을 전부 끊는 것만으로는 부족하다. 옛 비밀번호로 이미 검증을 통과한 로그인이 무효화가
-- 끝난 뒤에 세션을 만들면 그 세션은 끊긴 적이 없어 계속 재발급된다 — 비밀번호를 바꿨는데
-- 옛 비밀번호를 아는 사람이 그대로 남는다.
--
-- 그래서 로그인은 "비밀번호를 확인한 시점의 번호"를 세션에 적고, 재발급은 그것이 지금 번호와
-- 같은지 본다.
--
-- **비밀번호와 같은 행에 둔다.** 다른 저장소에 두면 두 가지가 어긋난다.
--   1) 해시와 번호를 따로 읽게 되어, 그 사이에 재설정이 끝나면 옛 해시에 새 번호가 붙는다.
--      그 세션은 검사를 통과한다.
--   2) 수명이 다르다. 번호가 먼저 사라지면 "한 번도 안 바꾼 상태"로 보여, 재설정 뒤에
--      정상적으로 로그인한 세션이 이유 없이 끊긴다.
-- 같은 행이면 한 번의 조회로 둘이 함께 오고, UPDATE 한 문장으로 함께 바뀐다.
alter table users
    add column credential_version bigint not null default 0;
